#!/usr/bin/env python3
"""Generate lookup tables from the vendored WHATWG registry and encoding index."""
import json
from pathlib import Path
import sys


def generate(source):
    labels = {}
    for group in json.loads(source.read_text(encoding="utf-8")):
        for encoding in group["encodings"]:
            for label in encoding["labels"]:
                if not label.isascii() or label != label.lower() or label in labels:
                    raise ValueError(f"Invalid or duplicate encoding label: {label!r}")
                labels[label] = encoding["name"]
    lines = [
        "/* Generated by utils/encoding/generate.py; do not edit.",
        " * Data: Copyright WHATWG (Apple, Google, Mozilla, Microsoft).",
        " * BSD-3-Clause; see utils/encoding/LICENSE. */",
        f"#define ENCODING_LABEL_MAX {max(map(len, labels))}",
        "static const struct {",
        "    const char *label, *name;",
        "} encoding_labels[] = {",
    ]
    lines += [f"    {{{json.dumps(label)}, {json.dumps(name)}}}," for label, name in sorted(labels.items())]
    lines += ["};", "", "static const struct {", "    uint32_t codepoint;", "    uint8_t byte;",
              "} mac_cyrillic[] = {"]
    reverse = {}
    pointers = set()
    for line in source.with_name("index-x-mac-cyrillic.txt").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        pointer, codepoint, *_ = line.split()
        pointer, codepoint = int(pointer), int(codepoint, 16)
        if pointer in pointers or not 0 <= pointer < 128 or not 128 <= codepoint <= 0x10ffff:
            raise ValueError(f"Invalid index entry: {line}")
        pointers.add(pointer)
        # The single-byte encoder uses the first pointer for a code point.
        reverse[codepoint] = min(reverse.get(codepoint, 256), pointer + 128)
    if len(pointers) != 128:
        raise ValueError("Incomplete Mac Cyrillic index")
    lines += [f"    {{0x{codepoint:04x}, 0x{byte:02x}}}," for codepoint, byte in sorted(reverse.items())]
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    output = Path(sys.argv[2])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generate(Path(sys.argv[1])), encoding="utf-8")
